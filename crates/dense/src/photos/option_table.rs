//! The options of `crispmesh-dense photos` as one table: the command-line parser
//! takes its flags, kinds and defaults from here, and `listing` gives the same
//! rows as JSON for generated forms (`crispmesh-dense run --describe`).

use serde_json::{json, Value};

/// One option. `scope` is where it belongs: `run`, `masks`, `cameras` (every
/// provider of that module), `masks:NAME` or `cameras:NAME` (one provider),
/// `tools`, `machine`, `deadlines`, `gates`. `kind` is `switch` (`--flag` /
/// `--no-flag`), `integer`, `number`, `text`, `choice`, `provider`, `path`
/// (a file), `directory`, `executable` or `path_list` (separated like `PATH`).
pub struct OptionSpec {
    pub flag: &'static str,
    pub scope: &'static str,
    pub kind: &'static str,
    /// The value used when the flag is absent, as it would be typed; `None`: no value, or one explained in `meaning`.
    pub default: Option<&'static str>,
    pub choices: &'static [&'static str],
    /// Environment variable read when the flag is absent.
    pub variable: Option<&'static str>,
    /// May be given several times.
    pub repeated: bool,
    pub meaning: &'static str,
}

